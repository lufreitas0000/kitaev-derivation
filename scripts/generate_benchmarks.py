"""Generate ACID provenance-stamped exchange benchmark tables comparing SymPy CAS vs. 66-state Fock oracle."""

from __future__ import annotations

import hashlib
import json
import os
import subprocess
from datetime import UTC, datetime
from pathlib import Path

import sympy as sp

from kitaev_derivation.services.exchange_extraction import derive_bond_exchange_symbolic
from kitaev_derivation.services.fourth_order_exchange import (
    compute_fourth_order_fock_exchange,
    compute_hexagon_ring_exchange,
)
from kitaev_derivation.services.sparse_fock_oracle import (
    compute_fock_schrieffer_wolff_exchange,
    compute_fock_soc_finite_exchange,
)

ROOT = Path(__file__).resolve().parents[1]


def _git_sha() -> str:
    res = subprocess.run(
        ["git", "rev-parse", "HEAD"],
        cwd=ROOT,
        capture_output=True,
        text=True,
        check=False,
    )
    sha = res.stdout.strip()
    return sha if len(sha) == 40 else "0" * 40


def _atomic_write_text(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_name(f".{path.name}.tmp.{os.getpid()}")
    tmp.write_text(text, encoding="utf-8")
    os.replace(tmp, path)


def main() -> int:
    U, J_H, t1, t2, t3, t4 = sp.symbols("U J_H t1 t2 t3 t4", real=True)
    sym_z = derive_bond_exchange_symbolic(
        "z", U, J_H, t2, t1=t1, t3=t3, t4=t4, convention="spin_12"
    )

    cases: list[tuple[str, float, float, float, float, float, float, float]] = [
        ("JK_JH0_cancel", 4.0, 0.0, 0.0, 0.25, 0.0, 0.0, 0.0),
        ("JK_pure_t2", 4.0, 0.6, 0.0, 0.25, 0.0, 0.0, 0.0),
        ("RLK_t1_t2_t3", 4.0, 0.6, 0.05, 0.25, -0.15, 0.0, 0.0),
        ("Trigonal_t4", 4.0, 0.6, 0.05, 0.25, -0.15, 0.04, 0.0),
        ("RuCl3_lam_0p15", 3.0, 0.48, 0.05, 0.16, -0.19, -0.02, 0.15),
    ]

    lines = [
        "# PROVENANCE: generated by scripts/generate_benchmarks.py (kitaev-derivation)",
        f"# TIMESTAMP_UTC: {datetime.now(UTC).isoformat()}",
        f"# GIT_SHA: {_git_sha()}",
        "# CONVENTION: spin_12 (H = sum J_{ab} S_i^a S_j^b on z-bond; Pauli = spin_12 / 4)",
        "regime U J_H t1 t2 t3 t4 lam_soc J_sym K_sym Gamma_sym Gp_sym J_fock_lam0 K_fock_lam0 max_abs_diff_lam0 J_fock_soc K_fock_soc max_soc_shift",
    ]
    summary_rows: list[dict[str, float | str]] = []
    for name, u_v, jh_v, t1_v, t2_v, t3_v, t4_v, lam_v in cases:
        subs = {U: u_v, J_H: jh_v, t1: t1_v, t2: t2_v, t3: t3_v, t4: t4_v}
        j_s = float(sym_z["J"].evalf(subs=subs))
        k_s = float(sym_z["K"].evalf(subs=subs))
        g_s = float(sym_z["Gamma"].evalf(subs=subs))
        gp_s = float(sym_z["Gamma_prime"].evalf(subs=subs))

        fock_lam0 = compute_fock_schrieffer_wolff_exchange(
            "z", u_v, jh_v, t2_v, t1=t1_v, t3=t3_v, t4=t4_v
        )
        max_diff_lam0 = max(
            abs(j_s - fock_lam0.J),
            abs(k_s - fock_lam0.K),
            abs(g_s - fock_lam0.Gamma),
            abs(gp_s - fock_lam0.Gamma_prime),
        )
        if lam_v > 0.0:
            fock_soc = compute_fock_soc_finite_exchange(
                "z", u_v, jh_v, lam_v, t2_v, t1=t1_v, t3=t3_v, t4=t4_v
            )
            j_soc, k_soc = fock_soc.J, fock_soc.K
            soc_shift = max(abs(j_soc - fock_lam0.J), abs(k_soc - fock_lam0.K))
        else:
            j_soc, k_soc = fock_lam0.J, fock_lam0.K
            soc_shift = 0.0

        lines.append(
            f"{name} {u_v:.4f} {jh_v:.4f} {t1_v:.4f} {t2_v:.4f} {t3_v:.4f} {t4_v:.4f} {lam_v:.4f} "
            f"{j_s:.10f} {k_s:.10f} {g_s:.10f} {gp_s:.10f} "
            f"{fock_lam0.J:.10f} {fock_lam0.K:.10f} {max_diff_lam0:.3e} "
            f"{j_soc:.10f} {k_soc:.10f} {soc_shift:.3e}"
        )
        summary_rows.append(
            {
                "regime": name,
                "lam_soc": lam_v,
                "J_sym": j_s,
                "K_sym": k_s,
                "Gamma_sym": g_s,
                "Gamma_prime_sym": gp_s,
                "J_fock_lam0": fock_lam0.J,
                "K_fock_lam0": fock_lam0.K,
                "max_abs_diff_lam0": max_diff_lam0,
                "J_fock_soc": j_soc,
                "K_fock_soc": k_soc,
                "max_soc_shift": soc_shift,
            }
        )

    dat_path = ROOT / "data" / "processed" / "benchmarks" / "exchange_vs_fock_oracle.dat"
    payload = "\n".join(lines) + "\n"
    _atomic_write_text(dat_path, payload)
    sha = hashlib.sha256(dat_path.read_bytes()).hexdigest()

    meta = {
        "schema_version": 1,
        "dataset": "exchange_vs_fock_oracle",
        "source_repo": "kitaev-derivation",
        "git_sha": _git_sha(),
        "sha256": sha,
        "unit_convention": "spin_12 (Pauli = spin_12 / 4 per qsl_conventions.json)",
        "geometry": "two-site z-bond t2g edge-sharing octahedra",
        "parameters": {"cases": summary_rows},
    }
    meta_path = dat_path.with_suffix(".meta.json")
    _atomic_write_text(meta_path, json.dumps(meta, indent=2) + "\n")
    print(f"Wrote {dat_path.relative_to(ROOT)} (sha256={sha[:12]}...)")

    # Wave 3 M2.2: Idealized Hubbard-Kanamori-SOC 2nd+4th order + 6-site ring exchange export
    material_cases: list[
        tuple[str, float, float, float, float, float, float, float, float, float, float]
    ] = [
        ("alpha_RuCl3_infSOC_ref", 3.0, 0.48, 0.0, 0.05, 0.16, -0.19, -0.02, 2.0, 0.10, 0.16),
        ("alpha_RuCl3_finSOC_0p15_ref", 3.0, 0.48, 0.15, 0.05, 0.16, -0.19, -0.02, 2.0, 0.10, 0.16),
        ("Na2IrO3_infSOC_ref", 2.0, 0.30, 0.0, 0.05, 0.25, -0.20, -0.01, 2.5, 0.15, 0.20),
        ("Na2IrO3_finSOC_0p40_ref", 2.0, 0.30, 0.40, 0.05, 0.25, -0.20, -0.01, 2.5, 0.15, 0.20),
    ]
    mat_lines = [
        "# PROVENANCE: generated by scripts/generate_benchmarks.py (kitaev-derivation M2.2)",
        f"# TIMESTAMP_UTC: {datetime.now(UTC).isoformat()}",
        f"# GIT_SHA: {_git_sha()}",
        "# CONVENTION: idealized Hubbard-Kanamori-SOC model parameters (not trigonal crystal-field DFT); spin_12 on z-bond",
        "material_ref U J_H lam_soc t1 t2 t3 t4 J2 K2 G2 Gp2 J4 K4 G4 Gp4 J_tot K_tot G_tot Gp_tot bdl_diff4 k_ring_wp ring_frob_norm ring_bdl_diff",
    ]
    mat_rows: list[dict[str, float | str]] = []
    for (
        label,
        u_v,
        jh_v,
        lam_v,
        t1_v,
        t2_v,
        t3_v,
        t4_v,
        u_hex,
        t_iso_hex,
        t_k_hex,
    ) in material_cases:
        res4 = compute_fourth_order_fock_exchange(
            "z", u_v, jh_v, lam_v, t2_v, t1=t1_v, t3=t3_v, t4=t4_v, convention="spin_12"
        )
        hex_res = compute_hexagon_ring_exchange(u_eff=u_hex, t_iso=t_iso_hex, t_kitaev=t_k_hex)
        mat_lines.append(
            f"{label} {u_v:.3f} {jh_v:.3f} {lam_v:.3f} {t1_v:.3f} {t2_v:.3f} {t3_v:.3f} {t4_v:.3f} "
            f"{res4.J2:.8f} {res4.K2:.8f} {res4.Gamma2:.8f} {res4.Gamma_prime2:.8f} "
            f"{res4.J4:.8f} {res4.K4:.8f} {res4.Gamma4:.8f} {res4.Gamma_prime4:.8f} "
            f"{res4.J_total:.8f} {res4.K_total:.8f} {res4.Gamma_total:.8f} {res4.Gamma_prime_total:.8f} "
            f"{res4.richardson_bdl_max_diff:.3e} {hex_res.k_ring_wp:.8e} {hex_res.ring_frobenius_norm:.8e} "
            f"{hex_res.resolvent_vs_bdl_max_diff:.3e}"
        )
        mat_rows.append(
            {
                "material_ref": label,
                "J2": res4.J2,
                "K2": res4.K2,
                "Gamma2": res4.Gamma2,
                "Gamma_prime2": res4.Gamma_prime2,
                "J4": res4.J4,
                "K4": res4.K4,
                "Gamma4": res4.Gamma4,
                "Gamma_prime4": res4.Gamma_prime4,
                "J_total": res4.J_total,
                "K_total": res4.K_total,
                "Gamma_total": res4.Gamma_total,
                "Gamma_prime_total": res4.Gamma_prime_total,
                "richardson_bdl_max_diff": res4.richardson_bdl_max_diff,
                "k_ring_wp": hex_res.k_ring_wp,
                "ring_frobenius_norm": hex_res.ring_frobenius_norm,
                "ring_bdl_diff": hex_res.resolvent_vs_bdl_max_diff,
            }
        )

    exp_dat = ROOT / "data" / "exports" / "extended_kitaev_material_couplings.dat"
    _atomic_write_text(exp_dat, "\n".join(mat_lines) + "\n")
    exp_sha = hashlib.sha256(exp_dat.read_bytes()).hexdigest()
    exp_meta = {
        "schema_version": 1,
        "dataset": "extended_kitaev_material_couplings",
        "source_repo": "kitaev-derivation",
        "git_sha": _git_sha(),
        "sha256": exp_sha,
        "unit_convention": "spin_12 (Pauli = spin_12 / 4; idealized Hubbard-Kanamori-SOC model parameters)",
        "geometry": "z-bond 66-state Fock 2nd+4th order BDL and 6-site 924-state Kramers hexagon",
        "parameters": {"cases": mat_rows},
    }
    _atomic_write_text(exp_dat.with_suffix(".meta.json"), json.dumps(exp_meta, indent=2) + "\n")
    print(f"Wrote {exp_dat.relative_to(ROOT)} (sha256={exp_sha[:12]}...)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
